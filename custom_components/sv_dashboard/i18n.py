def normalize_language(value: Any) -> str:
    """Resolve Home Assistant/browser language values to a supported catalog key."""

    candidate = str(value or "en").replace("_", "-").strip().lower()
    base = candidate.split("-", 1)[0]
    if base == "no":
        base = "nb"
    if base in _MESSAGES:
        return base
    return "en"


def language_for(hass: HomeAssistant) -> str:
    """Return the configured Home Assistant language in package-catalog form."""

    return normalize_language(getattr(hass.config, "language", None))


def text(hass: HomeAssistant, key: str, **values: Any) -> str:
    """Render a localized package-owned server-side string."""

    language = language_for(hass)
    template = _MESSAGES.get(language, _MESSAGES["en"]).get(
        key,
        _MESSAGES["en"].get(key, key),
    )
    try:
        return template.format(**values)
    except (KeyError, ValueError):
        return template
